<?php
/**
 * Нормализация ссылок на посты в Telegram-канале (в т.ч. с темами/топиками)
 * + прямые ссылки на скачивание файлов с Google Drive.
 *
 * ФОРМАТЫ ССЫЛОК НА ПОСТ В TELEGRAM (что принимаем в форме админки):
 *   1. Публичный канал, без тем:       https://t.me/channel_name/123
 *   2. Приватный канал, без тем:       https://t.me/c/1234567890/123
 *   3. Публичный канал С темами:       https://t.me/channel_name/45/123
 *      (45 — id темы/топика, 123 — id сообщения внутри темы)
 *   4. Приватный канал С темами:       https://t.me/c/1234567890/45/123
 *
 * Округляя ответ на вопрос из ТЗ: ХРАНИТЬ НУЖНО ИМЕННО ГОТОВУЮ ССЫЛКУ НА
 * СООБЩЕНИЕ, а не отдельно парсить ID и пересобирать её на лету. Причины:
 *   - Telegram сам умеет корректно открывать пост внутри темы по такой
 *     ссылке (и в приложении, и в браузере) — достаточно передать её как
 *     есть в <a href>, никакой доп. магии не требуется;
 *   - если позже вы врубите/выключите темы в канале или измените их
 *     структуру, готовая ссылка, скопированная в момент публикации поста,
 *     останется рабочей, а собранная "на коленке" из чистого ID — нет;
 *   - это ровно то, что Telegram даёт по кнопке "Copy Message Link" —
 *     никакого ручного парсинга ID не нужно, что проще и надёжнее.
 * Единственное, что реально нужно сайту — провалидировать формат при
 * сохранении (чтобы админ не вставил случайно ссылку-приглашение или
 * ссылку на весь топик без ID поста) и слегка нормализовать (обрезать
 * пробелы, привести к https, убрать query-параметры вида ?single).
 *
 * @return array{ok:bool, url:string, error?:string}
 */
function normalizeTelegramPostUrl(string $raw): array
{
    $url = trim($raw);
    if ($url === '') {
        return ['ok' => false, 'url' => '', 'error' => 'Ссылка пустая.'];
    }

    // Приглашение в чат (t.me/+xxx или t.me/joinchat/xxx) — это НЕ ссылка на пост.
    if (preg_match('~^https?://t\.me/(\+|joinchat/)~i', $url)) {
        return ['ok' => false, 'url' => '', 'error' => 'Это пригласительная ссылка на чат, а нужна ссылка на конкретный пост (кнопка "Copy Message Link" / "Скопировать ссылку" в Telegram).'];
    }

    if (!preg_match('~^https?://t\.me/~i', $url)) {
        return ['ok' => false, 'url' => '', 'error' => 'Ссылка должна начинаться с https://t.me/'];
    }

    // Приводим к https и убираем query/hash (?single, ?comment=... и т.п.)
    $url = preg_replace('~^http://~i', 'https://', $url);
    $url = preg_replace('~[?#].*$~', '', $url);
    $url = rtrim($url, '/');

    // c/<chat_id>/<msg_id> либо c/<chat_id>/<topic_id>/<msg_id>
    // channel_name/<msg_id> либо channel_name/<topic_id>/<msg_id>
    if (!preg_match('~^https://t\.me/(c/\d+/\d+(/\d+)?|[A-Za-z0-9_]{3,}/\d+(/\d+)?)$~', $url)) {
        return ['ok' => false, 'url' => '', 'error' => 'Не похоже на ссылку конкретного поста. В Telegram: зажмите сообщение → "Копировать ссылку" — и вставьте её целиком.'];
    }

    return ['ok' => true, 'url' => $url];
}

/**
 * Превращает ссылку Google Drive (webViewLink вида .../file/d/ID/view) в
 * прямую ссылку на скачивание файла, чтобы браузер сразу начинал загрузку
 * вместо открытия страницы предпросмотра Google Drive в новой вкладке.
 * Если ID не находится (ссылка уже "чужого" формата) — возвращает исходную.
 */
function driveDirectDownloadUrl(string $url): string
{
    $url = trim($url);
    if ($url === '') return '';
    if (preg_match('~/d/([A-Za-z0-9_-]{10,})~', $url, $m) || preg_match('~[?&]id=([A-Za-z0-9_-]{10,})~', $url, $m)) {
        return 'https://drive.google.com/uc?export=download&id=' . $m[1];
    }
    return $url;
}
